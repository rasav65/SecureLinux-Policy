def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


A = load(ADAPTER, "slp_auditd_rules_apply")
C = load(CHECK_ADAPTER, "slp_auditd_rules_check")

# Штатный rules.d/audit.rules пакета auditd на средах 1–7 (разведка 01.10.2026).
STOCK = b"## First rule - delete all\n-D\n\n## Increase the buffers to survive stress events.\n-b 8192\n\n-f 1\n\n--backlog_wait_time 60000\n"
CONTROL_LINES = (b"-D", b"-b", b"-f", b"--backlog_wait_time", b"-e")
NORMAL = dict(A.RULES)
NORMAL.update({normal: normal for _source, normal in A.RULES})


class Host:
    """Временный корень с каталогами auditd, штатными файлами правил и моделью ядра."""

    def __init__(self, td, kernel=(), enabled=1, load_rc=0):
        self.root = Path(td)
        self.audit = self.root / "etc/audit"
        self.rules_d = self.audit / "rules.d"
        self.rules_d.mkdir(parents=True)
        os.chmod(self.audit, 0o750)
        os.chmod(self.rules_d, 0o750)
        self.write(self.rules_d / "audit.rules", STOCK)
        self.audit_rules = self.audit / "audit.rules"
        self.write(self.audit_rules, b"## This file is automatically generated from /etc/audit/rules.d\n" + STOCK)
        self.product = self.rules_d / "50-securelinux-policy.rules"
        (self.root / "usr/sbin").mkdir(parents=True)
        self.kernel_file = self.root / "kernel"
        auditctl = self.root / "usr/sbin/auditctl"
        auditctl.write_text("#!/bin/sh\ncat '%s'\n" % self.kernel_file, encoding="utf-8")
        auditctl.chmod(0o755)
        augenrules = self.root / "usr/sbin/augenrules"
        augenrules.write_text("#!/bin/sh\nexit 0\n", encoding="ascii")
        augenrules.chmod(0o755)
        self.set_kernel(list(kernel))
        self.enabled = enabled
        self.load_rc = list(load_rc) if isinstance(load_rc, (list, tuple)) else [load_rc]
        self.after_load = None
        self.calls = []

    @staticmethod
    def write(path, data, mode=0o640):
        path.write_bytes(data)
        os.chmod(path, mode)

    def set_kernel(self, lines):
        self.kernel = list(lines)
        self.kernel_file.write_bytes(b"".join(line + b"\n" for line in self.kernel) if self.kernel else b"No rules\n")

    def augenrules(self):
        names = A.rule_file_names(os.listdir(os.fsencode(self.rules_d)))
        body = b"".join((self.rules_d / os.fsdecode(n)).read_bytes() for n in names)
        self.write(self.audit_rules, b"## This file is automatically generated from /etc/audit/rules.d\n" + body)
        loaded = []
        for line in body.split(b"\n"):
            line = line.strip()
            if not line or line.startswith(b"#") or line.split()[0] in CONTROL_LINES:
                continue
            rule = NORMAL.get(line, line)
            if rule in loaded:
                self.set_kernel(loaded)
                return 1
            loaded.append(rule)
        self.set_kernel(loaded)
        return 0

    def run(self, argv, timeout):
        self.calls.append(tuple(argv))
        if argv == [A.AUDITCTL, "-l"]:
            return subprocess.CompletedProcess(argv, 0, self.kernel_file.read_bytes(), b"")
        if argv == [A.AUDITCTL, "-s"]:
            out = b"enabled %d\nfailure 1\npid 713\nbacklog_limit 8192\n" % self.enabled
            return subprocess.CompletedProcess(argv, 0, out, b"")
        if argv == [A.AUGENRULES, "--load"]:
            rc = self.augenrules()
            forced = self.load_rc.pop(0) if self.load_rc else 0
            if self.after_load is not None:
                self.after_load(self)
            return subprocess.CompletedProcess(argv, forced or rc, b"", b"")
        raise AssertionError(argv)

    def execute(self, dry_run=False, privileged=True, key="table1", expected="present"):
        return A.execute_control("FSTEC-LOGGING-2025-APPENDIX2-LINUX-4-AUDIT-RULES", key, "eq", expected, True,
                                 dry_run=dry_run, privilege_check=lambda: privileged,
                                 _root=str(self.root), _run=self.run)

    def check(self):
        block = C._shell_function_for_fixture("AUD.R", str(self.rules_d), str(self.root / "usr/sbin/auditctl"))
        cp = subprocess.run([BASH, "-c", "set -u\n" + block + "\nslp_check_AUD_R\n"], text=True,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
        assert cp.returncode == 0, cp.stderr
        return cp.stdout.strip().split("\t")[2:]

    def loads(self):
        return sum(1 for call in self.calls if call == (A.AUGENRULES, "--load"))


