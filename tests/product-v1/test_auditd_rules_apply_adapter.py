        self.assertEqual([source.decode("ascii") for source, _normal in A.RULES], [r for r in rules if "myapp" not in r])
        self.assertIn('  kind: "auditd-rules"\n  locator: "/etc/audit/rules.d"\n  key: "table1"\n', text)
        self.assertIn('  op: "eq"\n  value: "present"\n', text)
        self.assertIn("apply:\n  supported: true\n", text)

