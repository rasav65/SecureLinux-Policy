class Refusals(unittest.TestCase):
    def refused(self, prepare, outcome, reason, **host_kwargs):
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td, **host_kwargs)
            prepare(host)
            snapshot = {p: p.read_bytes() for p in host.audit.rglob("*") if p.is_file() and not p.is_symlink()}
            res = host.execute()
            self.assertEqual((res["outcome"], res["reason"]), (outcome, reason), res)
            self.assertFalse(res["mutation_performed"])
            self.assertEqual(host.loads(), 0)
            self.assertEqual({p: p.read_bytes() for p in snapshot}, snapshot)
            return res

    def test_missing_tools(self):
        for tool in ("auditctl", "augenrules"):
            with self.subTest(tool=tool):
                self.refused(lambda h, t=tool: (h.root / "usr/sbin" / t).unlink(),
                             "ABORTED_PRECONDITION_OTHER", "tools:missing:" + tool)

    def test_untrusted_objects(self):
        cases = (
            (lambda h: os.chmod(h.rules_d, 0o770), "auditd-rules:dir-untrusted"),
            (lambda h: h.write(h.product, b"x\n", 0o660), "auditd-rules:untrusted"),
            (lambda h: os.symlink("/dev/null", h.product), "auditd-rules:untrusted"),
            (lambda h: os.link(h.audit_rules, h.root / "hard"), "auditd-rules:untrusted"),
            (lambda h: os.symlink("/dev/null", h.rules_d / "60-x.rules"), "auditd-rules:other-untrusted"),
            (lambda h: h.write(h.rules_d / "60-x.rules", b"-w /etc/hosts -k h\n", 0o666), "auditd-rules:other-untrusted"),
        )
        for prepare, reason in cases:
            with self.subTest(reason=reason):
                res = self.refused(prepare, "ABORTED_PRECONDITION_CONFLICT", reason)
                self.assertEqual(res["operator_decision"]["class"], "ADMIN_ACTION_REQUIRED")

    def test_rule_in_other_file_is_conflict(self):
        for line in (A.RULES[3][0], A.RULES[23][1]):
            with self.subTest(line=line):
                self.refused(lambda h, x=line: h.write(h.rules_d / "60-site.rules", x + b"\n"),
                             "ABORTED_PRECONDITION_CONFLICT", "auditd-rules:rule-in-other-file")

    def test_locked_rules(self):
        self.refused(lambda h: h.write(h.rules_d / "99-finalize.rules", b"-e 2\n"),
                     "ABORTED_PRECONDITION_CONFLICT", "auditd-rules:locked")
        self.refused(lambda h: None, "ABORTED_PRECONDITION_CONFLICT", "auditd-rules:locked", enabled=2)
        # Закомментированная строка и `-e 1` не блокируют.
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td)
            host.write(host.rules_d / "99-finalize.rules", b"# -e 2\n-e 1\n")
            self.assertEqual(host.execute()["outcome"], "APPLIED")

    def test_invalid_bytes_and_hidden_or_foreign_names(self):
        self.refused(lambda h: h.write(h.rules_d / "60-x.rules", b"\x00\n"),
                     "ABORTED_PRECONDITION_OTHER", "auditd-rules:invalid-bytes")
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td)
            # Не загружаются augenrules: скрытый файл и имя без окончания .rules.
            host.write(host.rules_d / ".60-x.rules", A.RULES[0][0] + b"\n", 0o666)
            host.write(host.rules_d / "60-x.rules.bak", A.RULES[0][0] + b"\n", 0o666)
            self.assertEqual(host.execute()["outcome"], "APPLIED")

    def test_kernel_list_failure(self):
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td)
            real = host.run

            def run(argv, timeout):
                if argv == [A.AUDITCTL, "-l"]:
                    return subprocess.CompletedProcess(argv, 1, b"", b"")
                return real(argv, timeout)

            host.run = run
            res = host.execute()
            self.assertEqual((res["outcome"], res["reason"]), ("ABORTED_PRECONDITION_OTHER", "auditctl:list-failed"))


class Compensation(unittest.TestCase):
    def assert_restored(self, host, res, before, kernel, reason, outcome="FAILED_NOT_COMMITTED"):
        self.assertEqual((res["outcome"], res["reason"]), (outcome, reason), res)
        self.assertTrue(res["mutation_performed"])
        self.assertEqual(res["transaction_commit"], "NOT_COMMITTED")
        if outcome == "FAILED_NOT_COMMITTED":
            self.assertFalse(host.product.exists())
            self.assertEqual(host.audit_rules.read_bytes(), before)
            self.assertEqual(host.kernel_file.read_bytes(), kernel)

    def test_load_failure_is_rolled_back(self):
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td, load_rc=[1, 0])
            before, kernel = host.audit_rules.read_bytes(), host.kernel_file.read_bytes()
            res = host.execute()
            self.assert_restored(host, res, before, kernel, "augenrules:load-failed")
            self.assertEqual(host.loads(), 2)

    def test_postcheck_failure_is_rolled_back(self):
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td)
            before, kernel = host.audit_rules.read_bytes(), host.kernel_file.read_bytes()

            def drop_one(h):
                if h.product.exists():
                    h.set_kernel(h.kernel[:-1])
                    h.after_load = None

            host.after_load = drop_one
            res = host.execute()
            self.assert_restored(host, res, before, kernel, "auditd-rules:postcheck-failed")

    def test_audit_rules_bytes_restored_after_load(self):
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            # audit.rules F1 не совпадает со склейкой rules.d: откат возвращает именно байты F1.
            host = Host(td, load_rc=[1, 0])
            host.write(host.audit_rules, b"## stale\n-D\n", 0o600)
            res = host.execute()
            self.assert_restored(host, res, b"## stale\n-D\n", b"No rules\n", "augenrules:load-failed")
            self.assertEqual(os.stat(host.audit_rules).st_mode & 0o7777, 0o600)

    def test_failed_rollback_is_compensation_failure(self):
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td, kernel=[b"-w /etc/hosts -p wa -k hosts"], load_rc=[1, 0])
            before = host.audit_rules.read_bytes()
            # Правило загружено вручную, в файлах его нет: augenrules при откате его не вернёт.
            res = host.execute()
            self.assert_restored(host, res, before, None, "augenrules:load-failed", outcome="FAILED_COMPENSATION")
            self.assertFalse(host.product.exists())

    def test_change_before_load_restores_product_without_load(self):
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td)
            real = A._write

            def write(root, path, data, refs, dirs, owner, mode, full=True):
                st = real(root, path, data, refs, dirs, owner, mode, full)
                if path == A.PRODUCT:
                    host.write(host.rules_d / "70-late.rules", b"-w /etc/hosts -k h\n")
                return st

            A._write = write
            try:
                res = host.execute()
            finally:
                A._write = real
            self.assertEqual((res["outcome"], res["reason"]),
                             ("FAILED_NOT_COMMITTED", "auditd-rules:changed-before-load"), res)
            self.assertEqual(host.loads(), 0)
            self.assertFalse(host.product.exists())

    def test_write_protocol_refuses_changed_object(self):
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td)
            dirs, files, others = A.observe(str(host.root))
            refs = {A.PRODUCT: None, A.AUDIT_RULES: A._tuple(files[A.AUDIT_RULES][0])}
            host.write(host.product, b"x\n", 0o600)
            with self.assertRaises(A._Changed):
                A._write(str(host.root), A.PRODUCT, A.PRODUCT_BYTES, refs, dirs, (os.geteuid(), os.getegid()), 0o640)
            host.product.unlink()
            # Новый файл правил в rules.d — тоже расхождение с F1.
            host.write(host.rules_d / "70-late.rules", b"-w /etc/hosts -k h\n")
            with self.assertRaises(A._Changed):
                A._write(str(host.root), A.PRODUCT, A.PRODUCT_BYTES, refs, dirs, (os.geteuid(), os.getegid()), 0o640)
            self.assertFalse(host.product.exists())
            self.assertFalse(Path(str(host.product) + A.TMP_SUFFIX).exists())


class Regressions(unittest.TestCase):
    """Регрессии: подмена каталога rules.d, файл продукта после загрузки отката, жёсткая ссылка
    у неизменяемого файла правил."""

    def test_b01_replaced_rules_dir_is_not_touched(self):
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td, load_rc=[1, 0])
            moved = host.audit / "rules.d.old"

            def swap(h):
                if moved.exists():
                    return
                os.rename(h.rules_d, moved)
                h.rules_d.mkdir()
                os.chmod(h.rules_d, 0o750)
                h.write(h.product, b"foreign\n")

            host.after_load = swap
            res = host.execute()
            self.assertEqual((res["outcome"], res["reason"]), ("FAILED_COMPENSATION", "augenrules:load-failed"), res)
            self.assertEqual(host.product.read_bytes(), b"foreign\n")
            self.assertEqual((moved / "50-securelinux-policy.rules").read_bytes(), A.PRODUCT_BYTES)

    def test_b02_product_reappearing_during_rollback_load(self):
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td, load_rc=[1, 0])
            loads = []

            def reappear(h):
                loads.append(1)
                if len(loads) == 2:
                    h.write(h.product, A.PRODUCT_BYTES)

            host.after_load = reappear
            res = host.execute()
            self.assertEqual((res["outcome"], res["reason"]), ("FAILED_COMPENSATION", "augenrules:load-failed"), res)
            self.assertTrue(host.product.exists())

    def test_b03_hard_link_of_read_only_rules_file_is_accepted(self):
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td)
            os.link(host.rules_d / "audit.rules", host.root / "audit.rules.link")
            res = host.execute()
            self.assertEqual(res["outcome"], "APPLIED", res)

    def test_unlink_checked_refuses_non_regular_and_swapped_dir(self):
        with tempfile.TemporaryDirectory(dir=ROOT) as td:
            host = Host(td)
            dirs, _files, _others = A.observe(str(host.root))
            host.product.mkdir()
            self.assertFalse(A._unlink_checked(str(host.root), A.PRODUCT, dirs))
            self.assertTrue(host.product.is_dir())
            host.product.rmdir()
            self.assertTrue(A._unlink_checked(str(host.root), A.PRODUCT, dirs))


