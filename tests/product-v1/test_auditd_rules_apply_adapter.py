        self.assertEqual(lines[2:-1], [source for source, _normal in A.RULES])
        self.assertTrue(all(line.startswith(b"# ") for line in lines[:2]))
        self.assertFalse(A.PRODUCT.endswith(A.TMP_SUFFIX))
